import type { CatalogProduct, CatalogVariant, PhotoStatus } from "./catalog";

function option(id: string, label: string, priceCents?: number, stockCount?: number): CatalogVariant {
  return {
    id,
    label,
    squareCatalogVariationId: null,
    ...(priceCents === undefined ? {} : { priceCents }),
    ...(stockCount === undefined ? {} : { stockCount }),
  };
}

function listing(input: {
  slug: string;
  sku: string;
  title: string;
  category: CatalogProduct["category"];
  department?: CatalogProduct["department"];
  priceCents: number;
  unit?: CatalogProduct["unit"];
  stockCount: number;
  stockLabel: string;
  image: string | null;
  imageAlt: string | null;
  gallery?: CatalogProduct["gallery"];
  photoStatus?: PhotoStatus;
  description: string;
  materials: string[];
  variants?: CatalogVariant[];
}): CatalogProduct {
  return {
    slug: input.slug,
    sku: input.sku,
    title: input.title,
    department: input.department ?? "body-jewelry",
    category: input.category,
    priceCents: input.priceCents,
    unit: input.unit ?? "each",
    stockCount: input.stockCount,
    stockLabel: input.stockLabel,
    image: input.image,
    imageAlt: input.imageAlt,
    gallery: input.gallery ?? [],
    photoStatus: input.photoStatus ?? (input.image ? "ready" : "needed"),
    description: input.description,
    materials: input.materials,
    variants: input.variants ?? [option("one", "One style")],
    featured: false,
    fulfillment: "square-catalog",
    reconnect: null,
    externalHref: null,
  };
}

